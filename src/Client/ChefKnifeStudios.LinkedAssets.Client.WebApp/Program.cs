using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
using ChefKnifeStudios.LinkedAssets.Client.WebApp;
using ChefKnifeStudios.LinkedAssets.Client.Shared.Services;
using Blazored.LocalStorage;
using MatBlazor;
using ChefKnifeStudios.LinkedAssets.Client.Core.Services;
using ChefKnifeStudios.LinkedAssets.Client.Shared.Services.JsInterop;
var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
builder.Services.AddScoped(_ => new HttpClient { BaseAddress = new Uri(builder.HostEnvironment.BaseAddress) });
builder.Services.AddMatBlazor();
builder.Services.AddBlazoredLocalStorage();
builder.Services.AddScoped<SettingsService>();
builder.Services.AddSingleton(TimeProvider.System);
builder.Services.AddScoped<IGeotabReadClient, GeotabReadClient>();
builder.Services.AddScoped<ISessionStore, SessionStorageJsInterop>();
builder.Services.AddScoped<GeotabSessionService>();
builder.Services.AddScoped<SourceReader>();
builder.Services.AddScoped<LinkedAssetsService>();
builder.Services.AddScoped<DeviceStatusService>();
builder.Services.AddScoped<ChefKnifeStudios.LinkedAssets.Client.Shared.ViewModels.LinkedAssetsViewModel>();
await builder.Build().RunAsync();
