import fs from 'node:fs/promises';
import {chromium} from '@playwright/test';
import {interceptGeotab} from './fixtures.js';
await fs.mkdir('../../artifacts/validation',{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:900}});
await interceptGeotab(page);
await page.route('**/appsettings.json',r=>r.fulfill({json:{Map:{LightStyleUrl:'/map-light.json',DarkStyleUrl:'/map-dark.json'}}}));
await page.route('**/map-*.json',r=>r.fulfill({json:{version:8,metadata:{theme:r.request().url().includes('dark')?'dark':'light'},sources:{},layers:[{id:'background',type:'background',paint:{'background-color':r.request().url().includes('dark')?'#263238':'#DDE3EB'}}]}}));
await page.goto('http://localhost:5180');
await page.getByLabel('Geotab username or email').fill('fixture');await page.getByLabel('Password',{exact:true}).fill('synthetic-only');await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.getByText('3 / 3 links').waitFor();
await page.waitForFunction(()=>document.querySelector('.graph-host')?._cyreg?.cy?.nodes(':childless').length===7);
await page.screenshot({path:'../../artifacts/validation/default.png'});
const point=await page.evaluate(()=>document.querySelector('.graph-host')._cyreg.cy.nodes(':parent').filter(n=>n.data('key')==='DeviceLink:same').children()[0].renderedPosition());
await page.evaluate(()=>{const Original=maplibregl.Map;maplibregl.Map=class extends Original{constructor(options){super(options);window.captureMap=this;}};});
await page.mouse.click(Math.round(point.x),Math.round(point.y));
await page.locator('.member-reports time').first().waitFor();
await page.waitForFunction(()=>window.captureMap?.getLayer('member-pins')&&new Set(captureMap.queryRenderedFeatures({layers:['member-pins']}).map(f=>f.properties.deviceId)).size===2);
await page.screenshot({path:'../../artifacts/validation/details.png'});
await page.getByRole('button',{name:'Dark theme',exact:true}).click();
await page.waitForFunction(()=>captureMap.getStyle()?.metadata?.theme==='dark'&&captureMap.getLayer('member-pins')&&new Set(captureMap.queryRenderedFeatures({layers:['member-pins']}).map(f=>f.properties.deviceId)).size===2);
await page.screenshot({path:'../../artifacts/validation/dark.png'});
await page.setViewportSize({width:390,height:844});
await page.waitForFunction(()=>captureMap.getCanvas().clientWidth===document.querySelector('.positions-map').clientWidth&&captureMap.getLayer('member-pins')&&new Set(captureMap.queryRenderedFeatures({layers:['member-pins']}).map(f=>f.properties.deviceId)).size===2);
await page.screenshot({path:'../../artifacts/validation/narrow.png'});
await browser.close();
